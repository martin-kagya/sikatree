import { chromium } from 'playwright-core';
const b = await chromium.launch({ channel: 'chrome' });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
await p.goto('http://127.0.0.1:3000/amasglow', { waitUntil: 'load' });
await p.waitForTimeout(600);
await p.locator('.shop-card').first().hover();
await p.locator('.shop-card').first().locator('.shop-add').click();
await p.locator('button[aria-label^="Cart,"].h-11').click();
await p.waitForTimeout(400);
await p.locator('dialog.shop-checkout input[name="name"]').fill('Kofi Mensah');
await p.locator('dialog.shop-checkout input[name="phone"]').fill('024 555 1234');
await p.locator('dialog.shop-checkout input[name="email"]').fill('kofi@example.com');
await p.locator('dialog.shop-checkout textarea[name="address"]').fill('12 Oxford Street, Osu, near the pharmacy');
await p.locator('dialog.shop-checkout button[type="submit"]').click();
await p.waitForTimeout(2200);
await p.screenshot({ path: '/tmp/final-success.png' });
console.log(await p.locator('dialog.shop-checkout').innerText().then((t) => t.slice(0, 200)));
await b.close();
