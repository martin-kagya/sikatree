import type { ReactNode, SVGProps } from 'react';

// Local icon set. The landing page needs twelve glyphs; shipping a full icon
// package cost ~16 kB gzipped for them, so they live here with the same
// 24px grid, round caps and stroke behaviour as before.

type IconProps = SVGProps<SVGSVGElement> & { strokeWidth?: number };

function Icon({ children, strokeWidth = 2, ...props }: IconProps & { children: ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      {children}
    </svg>
  );
}

